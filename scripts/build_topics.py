#!/usr/bin/env python3
"""Write evergreen topic hub pages (public/topics/*.html) from scripts/topics.json.

Each hub explains one recurring theme and links every issue on it in plain HTML, so search
visitors landing on a broad question ("is the four-year cycle still working?") can reach the
archive. Issues are assigned by keyword hits in title, dek and body, plus pinned/include ids,
so new letters join the right hubs when publish_letter.py reruns.
"""

from __future__ import annotations

import html
import json
import re
from datetime import date
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / "public"
ISSUES = PUBLIC / "issues"
OUT = PUBLIC / "topics"
CONFIG = Path(__file__).resolve().parent / "topics.json"
INDEX = PUBLIC / "index.html"
SITE = "https://www.paramariboletter.com"
BRAND = "The Paramaribo Letter"
TOPICS_START = "<!-- topics:start (generated by scripts/build_topics.py) -->"
TOPICS_END = "<!-- topics:end -->"
TAG_RE = re.compile(r"<[^>]+>")


def esc(value: str) -> str:
    return html.escape(value or "", quote=True)


def fmt_date(iso: str) -> str:
    try:
        day = date.fromisoformat(iso)
    except ValueError:
        return iso
    return f"{day.strftime('%B')} {day.day}, {day.year}"


def issue_url(issue_id: str) -> str:
    return f"/issue?id={quote(issue_id, safe='')}"


def topic_url(slug: str) -> str:
    return f"/topics/{slug}"


def json_ld(data: dict) -> str:
    text = json.dumps(data, ensure_ascii=False, indent=2).replace("<", "\\u003c")
    return f'<script type="application/ld+json">\n{text}\n  </script>'


def load_topics() -> list[dict]:
    return json.loads(CONFIG.read_text())


def load_issues() -> list[dict]:
    rows = []
    for path in ISSUES.glob("*.json"):
        meta = json.loads(path.read_text())
        body_path = path.with_suffix(".body.html")
        meta["body"] = body_path.read_text() if body_path.exists() else ""
        rows.append(meta)
    rows.sort(key=lambda row: (row.get("date") or "", row.get("id") or ""), reverse=True)
    return rows


def assign(rows: list[dict], topics: list[dict] | None = None) -> dict[str, list[dict]]:
    """Map topic slug -> issues on that topic, newest first."""
    topics = topics if topics is not None else load_topics()
    out: dict[str, list[dict]] = {}
    for topic in topics:
        pattern = re.compile(topic["pattern"], re.I)
        forced = set(topic.get("pinned", [])) | set(topic.get("include", []))
        matched = []
        for row in rows:
            text = " ".join([row.get("title") or "", row.get("dek") or "", TAG_RE.sub(" ", row.get("body") or "")])
            if row["id"] in forced or len(pattern.findall(text)) >= topic.get("min_hits", 1):
                matched.append(row)
        out[topic["slug"]] = matched
    return out


def topics_for_issue(issue_id: str, assigned: dict[str, list[dict]], topics: list[dict]) -> list[dict]:
    return [t for t in topics if any(r["id"] == issue_id for r in assigned.get(t["slug"], []))]


def topic_links_html(topics: list[dict]) -> str:
    """Inline 'Topics:' line for issue pages."""
    if not topics:
        return ""
    links = " · ".join(f'<a href="{esc(topic_url(t["slug"]))}">{esc(t["name"])}</a>' for t in topics)
    return f'<p class="topic-links">Topics: {links}</p>'


def card_html(row: dict) -> str:
    """Same markup as cardHTML() in public/app.js."""
    return f"""
      <a class="feed-card" href="{esc(issue_url(row['id']))}">
        <img src="/{esc((row.get('cover') or 'images/masthead.png').lstrip('/'))}" alt="" loading="lazy" decoding="async">
        <div>
          <div class="feed-kicker">{esc(row.get('kicker') or '')}</div>
          <h3>{esc(row.get('title') or row['id'])}</h3>
          <p>{esc(row.get('dek') or '')}</p>
          <div class="feed-meta">{esc(fmt_date(row.get('date') or ''))} · {esc(row.get('byline') or BRAND)}</div>
        </div>
      </a>"""


