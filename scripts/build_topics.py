def breadcrumb_ld(items: list[tuple[str, str]]) -> dict:
    return {
        "@context": "https://schema.org",
        "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": i + 1, "name": name, "item": url} for i, (name, url) in enumerate(items)
        ],
    }


def render_topic(topic: dict, rows: list[dict], topics: list[dict]) -> str:
    slug = topic["slug"]
    canonical = f"{SITE}{topic_url(slug)}"
    by_id = {r["id"]: r for r in rows}
    pinned = [by_id[i] for i in topic.get("pinned", []) if i in by_id]
    collection = {
        "@context": "https://schema.org",
        "@type": "CollectionPage",
        "name": topic["title"],
        "description": topic["description"],
        "url": canonical,
        "isPartOf": {"@type": "WebSite", "name": BRAND, "url": f"{SITE}/"},
        "dateModified": rows[0].get("date") if rows else "",
        "mainEntity": {
            "@type": "ItemList",
            "numberOfItems": len(rows),
            "itemListElement": [
                {
                    "@type": "ListItem",
                    "position": i + 1,
                    "url": f"{SITE}/issue?id={quote(r['id'], safe='')}",
                    "name": r.get("title") or r["id"],
                }
                for i, r in enumerate(rows)
            ],
        },
    }
    crumbs = breadcrumb_ld([("Home", f"{SITE}/"), ("Topics", f"{SITE}/topics"), (topic["name"], canonical)])
    ld = json_ld(collection) + "\n  " + json_ld(crumbs)
    intro = "\n".join(f"        <p>{esc(p)}</p>" for p in topic.get("intro", []))
    questions = "\n".join(f"          <li>{esc(q)}</li>" for q in topic.get("questions", []))
    start = "".join(card_html(r) for r in pinned)
    items = "\n".join(
        f'        <li><a href="{esc(issue_url(r["id"]))}">{esc(r.get("title") or r["id"])}</a>'
        f' <span class="more-letters-date">{esc(fmt_date(r.get("date") or ""))}</span>'
        f'<br><span class="topic-item-dek">{esc(r.get("dek") or "")}</span></li>'
        for r in rows
    )
    others = " · ".join(
        f'<a href="{esc(topic_url(t["slug"]))}">{esc(t["name"])}</a>' for t in topics if t["slug"] != slug
    )
    updated = fmt_date(rows[0].get("date") or "") if rows else ""
    return f"""{head_html(f"{topic['title']} · {BRAND}", topic["description"], canonical, ld)}
<body data-nav="topics">
  <div class="portal-stage wrap">
    <article class="topic-page">
      <nav class="topic-crumbs" aria-label="Breadcrumb"><a href="/">Home</a> › <a href="/topics">Topics</a> › {esc(topic["name"])}</nav>
      <h1>{esc(topic["title"])}</h1>
      <p class="lede">{esc(topic["dek"])}</p>
      <div class="meta">{len(rows)} letters · updated {esc(updated)}</div>
      <div class="body topic-intro">
{intro}
      </div>
      <aside class="topic-questions">
        <h2>Questions this page answers</h2>
        <ul>
{questions}
        </ul>
      </aside>
    </article>
    <section class="feed-head"><h2>Start here</h2></section>
    <div class="feed">{start}
    </div>
    <nav class="more-letters" aria-label="Every letter on this topic">
      <h2>Every letter on {esc(topic["name"].lower())}</h2>
      <ul>
{items}
      </ul>
      <p>More topics: {others}</p>
      <p><a href="/">All letters</a> · <a href="/charts">Charts</a> · <a href="/cases">Case studies</a></p>
    </nav>
    <p class="disclaimer">Educational scenario research. Not personalized financial advice. Levels and weights are as written in each dated letter; older issues stay in the archive unchanged.</p>
{SUBSCRIBE_AND_FOOTER}"""


def render_index(topics: list[dict], assigned: dict[str, list[dict]]) -> str:
    canonical = f"{SITE}/topics"
    title = f"Bitcoin and Macro Research by Topic · {BRAND}"
    description = (
        "Browse The Paramaribo Letter by topic: Bitcoin's four-year cycle, crash and bottom scenarios, "
        "ETF flows and leverage, the Fed and the yen, and the support and resistance map."
    )
    crumbs = breadcrumb_ld([("Home", f"{SITE}/"), ("Topics", canonical)])
    cards = "\n".join(
        f"""      <a class="topic-card" href="{esc(topic_url(t['slug']))}">
        <h2>{esc(t['title'])}</h2>
        <p>{esc(t['dek'])}</p>
        <span class="feed-meta">{len(assigned.get(t['slug'], []))} letters</span>
      </a>"""
        for t in topics
    )
    return f"""{head_html(title, description, canonical, json_ld(crumbs))}
<body data-nav="topics">
  <div class="portal-stage wrap">
    <section class="feed-head">
      <h1>Topics</h1>
      <span class="feed-toggle">Evergreen guides to the archive</span>
    </section>
    <p class="cases-intro">Each topic page explains one recurring question in plain language and links every letter that works on it, newest first. Start with the theme you came for.</p>
    <div class="topic-grid">
{cards}
    </div>
{SUBSCRIBE_AND_FOOTER}"""


def write_home_topics(topics: list[dict], assigned: dict[str, list[dict]]) -> None:
    text = INDEX.read_text()
    if TOPICS_START not in text or TOPICS_END not in text:
        print("index.html has no topics markers; skipped homepage topics")
        return
    head, rest = text.split(TOPICS_START, 1)
    _, tail = rest.split(TOPICS_END, 1)
    links = "".join(
        f'\n        <li><a href="{esc(topic_url(t["slug"]))}">{esc(t["name"])}</a></li>'
        for t in topics
    )
    block = f"""
    <section class="home-topics" aria-labelledby="topics-title">
      <h2 id="topics-title">Browse by topic</h2>
      <ul class="topic-chips">{links}
        <li><a href="/topics">All topics</a></li>
      </ul>
    </section>
    """
    INDEX.write_text(f"{head}{TOPICS_START}{block}{TOPICS_END}{tail}")
    print("wrote homepage topics")


def sitemap_entries() -> list[tuple[str, str | None]]:
    """(url, lastmod) pairs for build_feeds.py."""
    topics = load_topics()
    assigned = assign(load_issues(), topics)
    newest = [rows[0].get("date") for rows in assigned.values() if rows]
    entries = [(f"{SITE}/topics", max(newest) if newest else None)]
    for t in topics:
        rows = assigned.get(t["slug"], [])
        entries.append((f"{SITE}{topic_url(t['slug'])}", rows[0].get("date") if rows else None))
    return entries


def main() -> int:
    topics = load_topics()
    rows = load_issues()
    assigned = assign(rows, topics)
    OUT.mkdir(parents=True, exist_ok=True)
    keep = {"index.html"}
    for topic in topics:
        dest = OUT / f"{topic['slug']}.html"
        dest.write_text(render_topic(topic, assigned[topic["slug"]], topics))
        keep.add(dest.name)
        print(f"wrote {dest.relative_to(ROOT)} ({len(assigned[topic['slug']])} letters)")
    (OUT / "index.html").write_text(render_index(topics, assigned))
    print(f"wrote {(OUT / 'index.html').relative_to(ROOT)}")
    for stale in OUT.glob("*.html"):
        if stale.name not in keep:
            stale.unlink()
            print(f"removed {stale.relative_to(ROOT)}")
    write_home_topics(topics, assigned)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
